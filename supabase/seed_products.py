def main() -> None:
    url = os.getenv("SUPABASE_URL")
    key = os.getenv("SUPABASE_KEY")
    if not url or not key:
        print("SUPABASE_URL / SUPABASE_KEY not set", file=sys.stderr)
        return

    client = create_client(url, key)
    existing = client.table("products").select("name").is_("user_id", "null").execute().data
    existing_names = {row["name"] for row in existing}

    rows = [
        {
            "name": name,
            "calories": cal,
            "protein": protein,
            "fat": fat,
            "carbs": carbs,
            "user_id": None,
        }
        for name, cal, protein, fat, carbs in PRODUCTS
        if name not in existing_names
    ]

    if not rows:
        print("Nothing to insert; base already seeded.")
        return

    client.table("products").insert(rows).execute()
    print(f"Inserted {len(rows)} products.")


if __name__ == "__main__":
    main()
