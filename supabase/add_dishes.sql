create table if not exists public.dishes (
  id bigint generated by default as identity primary key,
  user_id bigint,
  name text not null,
  total_grams double precision not null default 0,
  calories double precision not null default 0,
  protein double precision not null default 0,
  fat double precision not null default 0,
  carbs double precision not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.dish_items (
  id bigint generated by default as identity primary key,
  dish_id bigint not null references public.dishes (id) on delete cascade,
  name text not null,
  grams double precision not null,
  calories double precision not null default 0,
  protein double precision not null default 0,
  fat double precision not null default 0,
  carbs double precision not null default 0
);
create index if not exists dish_items_dish_idx on public.dish_items (dish_id);
alter table public.dishes enable row level security;
alter table public.dish_items enable row level security;
create policy "dishes_read" on public.dishes for select to anon, authenticated using (true);
create policy "dishes_write" on public.dishes for insert to anon, authenticated with check (true);
create policy "dishes_update" on public.dishes for update to anon, authenticated using (true) with check (true);
create policy "dishes_delete" on public.dishes for delete to anon, authenticated using (true);
create policy "dish_items_read" on public.dish_items for select to anon, authenticated using (true);
create policy "dish_items_write" on public.dish_items for insert to anon, authenticated with check (true);
create policy "dish_items_update" on public.dish_items for update to anon, authenticated using (true) with check (true);
create policy "dish_items_delete" on public.dish_items for delete to anon, authenticated using (true);
