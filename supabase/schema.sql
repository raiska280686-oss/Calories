create table if not exists public.profiles (
  user_id    bigint primary key,
  username   text,
  sex        text not null,
  age        integer not null,
  height     double precision not null,
  weight     double precision not null,
  activity   integer not null,
  bmr        double precision not null,
  tdee       double precision not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id         bigint generated by default as identity primary key,
  user_id    bigint,
  name       text not null,
  calories   double precision not null,
  protein    double precision not null default 0,
  fat        double precision not null default 0,
  carbs      double precision not null default 0,
  brand      text,
  created_at timestamptz not null default now()
);

create index if not exists products_name_idx on public.products (lower(name));

create table if not exists public.diary_entries (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null,
  entry_date date not null,
  meal       text not null,
  product_id bigint references public.products (id) on delete set null,
  name       text not null,
  grams      double precision not null,
  calories   double precision not null,
  protein    double precision not null default 0,
  fat        double precision not null default 0,
  carbs      double precision not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists diary_user_date_idx on public.diary_entries (user_id, entry_date);

create table if not exists public.dishes (
  id          bigint generated by default as identity primary key,
  user_id     bigint,
  name        text not null,
  total_grams double precision not null default 0,
  calories    double precision not null default 0,
  protein     double precision not null default 0,
  fat         double precision not null default 0,
  carbs       double precision not null default 0,
  created_at  timestamptz not null default now()
);

create table if not exists public.dish_items (
  id         bigint generated by default as identity primary key,
  dish_id    bigint not null references public.dishes (id) on delete cascade,
  name       text not null,
  grams      double precision not null,
  calories   double precision not null default 0,
  protein    double precision not null default 0,
  fat        double precision not null default 0,
  carbs      double precision not null default 0
);

create index if not exists dish_items_dish_idx on public.dish_items (dish_id);

