insert into storage.buckets (id, name, public) values ('photos', 'photos', true) on conflict (id) do update set public = true;
drop policy if exists "photos_public_read" on storage.objects;
drop policy if exists "photos_anon_insert" on storage.objects;
drop policy if exists "photos_anon_update" on storage.objects;
drop policy if exists "photos_anon_delete" on storage.objects;
create policy "photos_public_read" on storage.objects for select using (bucket_id = 'photos');
create policy "photos_anon_insert" on storage.objects for insert to anon with check (bucket_id = 'photos');
create policy "photos_anon_update" on storage.objects for update to anon using (bucket_id = 'photos') with check (bucket_id = 'photos');
create policy "photos_anon_delete" on storage.objects for delete to anon using (bucket_id = 'photos');
